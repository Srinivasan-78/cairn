#!/usr/bin/env python3
"""
build_persona_models.py - Bake USER_PROFILE.md into the local models.

Re-bakes each srini-* tag in place so its Modelfile carries the operator profile
as its SYSTEM block, and every local session starts already knowing the hardware
ceiling, the stack, and the working preferences - with no fine-tuning.

Why a system prompt and not training: the profile is *facts*, and facts change.
A SYSTEM block is corrected by editing one file and rebuilding in ~2 seconds;
a fact baked into LoRA weights needs a retrain to undo, and a small model will
still contradict it whenever the prompt pulls the other way. Train style and
skills (that is what teacher_pipeline does); prompt the facts.

Derived tags are free in disk terms - Ollama reuses the base model's blobs and
only stores the new Modelfile.

CLI:
    python profile/build_persona_models.py              # rebuild all seven
    python profile/build_persona_models.py --model 9b   # just one
    python profile/build_persona_models.py --show       # print the SYSTEM block
    python profile/build_persona_models.py --dry-run
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

_DEFAULT_MODELS_DIR = Path(r"E:\LocalLLM\models")
if _DEFAULT_MODELS_DIR.exists():
    os.environ.setdefault("OLLAMA_MODELS", str(_DEFAULT_MODELS_DIR))
os.environ.setdefault("OLLAMA_HOST", "127.0.0.1:11434")

PROFILE = Path(__file__).with_name("USER_PROFILE.md")
# Project inventory, repo paths and shipping conventions. Second file rather
# than one giant profile so the operator facts and the project facts can be
# edited and reviewed independently.
PROJECTS = Path(__file__).with_name("PROJECTS.md")
# Full account inventory, generated by sync_repos.py - never hand-edited.
# Excluded from inference prompts by default to keep prompt evaluation sub-second.
REPOS = Path(__file__).with_name("REPOS.md")
BUILD_DIR = Path(__file__).with_name("build")

# alias -> (tag to read FROM, tag to write). Renamed 2026-11-26: the lineup now
# carries purpose-based names (what the model is FOR) rather than its upstream
# vendor identity, and the upstream tags were removed - see pull-model.ps1.
#
# Both halves are the same srini tag because the profile is re-baked in place,
# so `ollama list` stays one row per model with no duplicates.
#
# Consequence of dropping the upstream names: `ollama pull qwen3.5:9b` now
# re-adds *that* tag and leaves srini-coder:9b untouched, so adopting a new
# upstream build is two steps - `ollama cp <upstream> <srini tag>`, then re-run
# this script to put the SYSTEM block back. The old one-step "re-run after any
# pull" no longer applies.
#
# The alias keys are deliberately unchanged, so `--model 9b` and `--model
# granite3b` keep working from muscle memory and from any existing script.
TARGETS = {
    "4b": ("srini-draft:4b", "srini-draft:4b"),
    "9b": ("srini-coder:9b", "srini-coder:9b"),
    "35b": ("srini-deep:35b", "srini-deep:35b"),
    # Added 2026-11-24. srini-tools (granite4.2) is text-only but built for tool
    # calling and structured JSON; srini-vision (gemma4 e2b) adds image and audio
    # input. Both are smaller than the 9b, so they leave more of the 6.6 GB
    # usable budget for KV cache.
    "granite8b": ("srini-tools:8b", "srini-tools:8b"),
    "granite3b": ("srini-tools:3b", "srini-tools:3b"),
    # Was built from the upstream `gemma4:e2b-it-qat`; now re-baked in place.
    "gemma2b": ("srini-vision:2b", "srini-vision:2b"),
    # 30B MoE, 3B active. At 25 GB it cannot fit 8 GB of VRAM, so Ollama spills
    # the rest to system RAM - slow, but only 3B parameters are active per token,
    # which is what keeps a partially offloaded model usable at all.
    "nemotron": ("srini-bulk:30b", "srini-bulk:30b"),
}

# The lean block is the default because answer latency matters more here than
# completeness: every request in a harness re-sends the system prompt, and the
# full profile is ~1.5k tokens against ~400 for this. Only facts that change an
# answer survive the cut - the VRAM ceiling, which checkout is authoritative,
# how work is verified, and the house answer style.
LEAN_BLOCK = """You are a coding assistant on Srini's own Windows 11 machine.

Hardware: RTX 4060 Ti, 8 GB VRAM, of which ~6.6 GB is usable (the desktop
compositor holds ~1.4 GB). Ryzen 7 5700X, 64 GB RAM. Never propose a model or a
training run that does not fit 6.6 GB, and show the arithmetic when sizing one.

Stack: Ollama on Windows for inference (no /v1 suffix on the base URL - the
client appends /v1/messages itself). Training runs in WSL2 only; Unsloth and
bitsandbytes are unreliable on native Windows. Work lives on E:.

Main project: repo2graph - a Python 3.11+ code-graph and MCP server. The
authoritative checkout is E:\\Github\\repo2graph (v5.0.0); the copy at
C:\\Users\\Srini\\code\\repo2graph is two major versions stale, so never quote
versions or flags from it. Verify changes with `uv run ruff check .`,
`uv run python -m mypy repo2graph`, `uv run pytest` (or `make lint/typecheck/test`
where GNU make is available) - cheapest first. Conventional-commit titles phrased
as statements. Never add co-author or "generated by" trailers to commits.

Offline knowledge: when an `mcp__zimrag__zim_search` tool is present, it searches 441 GB of
local Kiwix archives (Wikipedia, Stack Overflow, devdocs, Arch wiki, libretexts,
Gutenberg - 70M articles). For any question of external fact - documentation,
science, history, software behaviour, definitions - you MUST call mcp__zimrag__zim_search
first and answer from the passages it returns. Do NOT answer such questions from
memory: on this machine, training 745 facts into a LoRA gave 19% exact recall, so
an uncited specific is probably wrong. Its passages arrive numbered [1], [2];
every claim taken from them must end with that number, like "mercury boils at
356.73 C [1]". Skip the tool only for code generation and for questions about
the current conversation or files.

Style: answer directly and concisely. Do not emit <think> blocks on direct
questions - start with the answer. Show the arithmetic for any hardware or cost
claim. Never claim something works without having verified it; say plainly when
a step failed or was skipped.
"""

def _da_name() -> str:
    """Read [da].name from LifeOS LIFEOS_CONFIG.toml, defaulting to Aria."""
    cfg = Path.home() / ".claude" / "LIFEOS" / "USER" / "CONFIG" / "LIFEOS_CONFIG.toml"
    if cfg.exists():
        text = cfg.read_text(encoding="utf-8", errors="replace")
        m = re.search(r'(?ms)^\[da\]\s.*?^name\s*=\s*"([^"]+)"', text)
        if m and m.group(1).strip():
            return m.group(1).strip()
    return "Aria"


# Compact LifeOS operating contract (~160 tokens) baked into every srini-* tag
# so local sessions follow LifeOS's Current->Ideal loop and response format
# without paying the ~10k-token full LIFEOS_SYSTEM_PROMPT.md cost on every turn.
def _lifeos_block() -> str:
    da = _da_name()
    return f"""LifeOS Operating Contract:
- Role: You are {da}, Srini's local Digital Assistant (DA) in LifeOS. Speak in first person ("I", "my"); address Srini as "you".
- Local inference only: you cannot fine-tune your own weights in-session; training runs offline in E:\\LocalLLM\\teacher_pipeline (WSL2).
- The One Loop: Move from Current State to Ideal State using verifiable criteria (ISA). Verify every change with real evidence before claiming done.
- Output Format:
  1. Lead directly with the answer (short, high-signal, no preamble).
  2. When work mutated files/state, include:
     🔧 CHANGE: (short bullets of what changed)
     ✅ VERIFY: (short bullets of observed verification evidence)
  3. Include ❓ OPEN: only for genuine blockers or decisions for you.
  4. End with one closing line: 🗣️ {da}: <one-line summary>
"""

# Confidence markers are for the human reader; they cost tokens and invite a
# small model to hedge, so they are stripped from what the model actually sees.
MARKER_RE = re.compile(r"\s*`\[(?:verified|inferred)[^\]]*\]`")

PREAMBLE = """You are a coding assistant running locally on Srini's own machine, \
for Srini's own work. The following is established context about your operator \
and their environment. Treat it as fact, not as a request to role-play. Do not \
recite it back; use it to skip questions you already have the answer to, and to \
avoid proposing anything that the hardware ceiling or the local stack rules out.

CRITICAL INSTRUCTIONS:
- Answer directly, immediately, and concisely.
- DO NOT output internal monologue or <think>...</think> blocks on direct queries. Start immediately with the answer.
- Always show arithmetic for VRAM/hardware calculations respecting the 6.6 GB usable VRAM ceiling (8 GB physical minus 1.4 GB Windows compositor).
- Never fabricate success or claim work is done without verification.

"""


def _reduce(text: str) -> str:
    """Strip the parts of a profile file that address the human, not the model."""
    text = MARKER_RE.sub("", text)
    # Drop the file's own maintenance instructions - they address the human.
    text = re.sub(
        r"^This file is the single source of truth.*?takes effect on the next call\.\s*",
        "",
        text,
        flags=re.DOTALL | re.MULTILINE,
    )
    text = re.sub(r"^Each entry is marked with.*?confirming\.\s*", "", text,
                  flags=re.DOTALL | re.MULTILINE)
    # Drop meta developer notes that don't belong in model context
    text = re.sub(
        r"## Why these facts are prompted, not trained.*",
        "",
        text,
        flags=re.DOTALL | re.MULTILINE,
    )
    text = text.replace("\n---\n", "\n")
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def system_block(
    *, include_repos: bool = False, lean: bool = False, include_lifeos: bool = True
) -> str:
    """The profile files, reduced to what is useful to a model at inference time.

    `lean` returns the ~400-token essentials instead of the ~1.5k-token profile.
    REPOS.md (a 38-table repo dump) is omitted unless asked for, so prompt
    evaluation stays immediate.
    """
    if lean:
        base = LEAN_BLOCK.strip()
        if include_lifeos:
            base = base + "\n\n" + _lifeos_block().strip()
        return base + "\n"

    parts = [_reduce(PROFILE.read_text(encoding="utf-8"))]
    if PROJECTS.exists():
        parts.append(_reduce(PROJECTS.read_text(encoding="utf-8")))
    if include_repos and REPOS.exists():
        parts.append(_reduce(REPOS.read_text(encoding="utf-8")))
    if include_lifeos:
        parts.append(_lifeos_block().strip())
    return PREAMBLE + "\n\n".join(parts)


# num_ctx per model, measured on the 8 GB card 2026-11-25 (ollama ps footprint and
# GPU/CPU split at each size). A flat 8192 was wrong in both directions: it starved
# the small models of 8-16x the context they can hold entirely on the GPU, and it
# was still too small for Claude Code on any of them, because a full system prompt
# measures ~25.6k tokens and Ollama 400s anything past num_ctx.
#
# The small models keep 100% GPU placement at these sizes. The 8b/9b and the two
# spill-regardless MoEs get 32768: they drop to ~75-81% GPU, which costs speed, but
# 8192 could not hold a session at all. Use --bare (a ~1k prompt) for the fast path.
# Keyed by the WRITTEN tag, because that is what modelfile() looks up - these
# were renamed with the lineup on 2026-11-26. A stale key here does not error,
# it silently falls through to DEFAULT_NUM_CTX and costs the small models the
# context they measured as holding entirely on the GPU.
NUM_CTX = {
    "srini-vision:2b": 131072,              # 2.0 GB, 100% GPU - sliding-window KV
    "srini-draft:4b": 65536,                # 4.5 GB, 100% GPU
    "srini-tools:3b": 65536,                # 5.2 GB, 100% GPU
    "srini-coder:9b": 32768,                # 6.9 GB, 81% GPU (8192 was the GPU-only max)
    "srini-tools:8b": 32768,                # 74% GPU
    "srini-deep:35b": 32768,                # MoE, spills regardless
    "srini-bulk:30b": 32768,                # 25 GB, spills regardless
}
DEFAULT_NUM_CTX = 32768
TEMPERATURE = {
    "srini-tools:3b": 0.2,
    "srini-vision:2b": 0.2,
}
DEFAULT_TEMPERATURE = 0.3

# Upstream registry name -> srini tag (single source of truth for pull-model.ps1).
UPSTREAM_ADOPT = {
    "qwen3.5:4b": "srini-draft:4b",
    "qwen3.5:9b": "srini-coder:9b",
    "qwen3.5:35b": "srini-deep:35b",
    "granite4.2:3b": "srini-tools:3b",
    "granite4.2:8b": "srini-tools:8b",
    "gemma4:e2b-it-qat": "srini-vision:2b",
    "nemotron-3.5-lightning:30b": "srini-bulk:30b",
}


def modelfile(base: str, system: str, derived: str = "", temperature: float | None = None) -> str:
    # Triple-quoted SYSTEM so the markdown's own quotes and newlines survive.
    num_ctx = NUM_CTX.get(derived, DEFAULT_NUM_CTX)
    temp = TEMPERATURE.get(derived, DEFAULT_TEMPERATURE) if temperature is None else temperature
    return (
        f"FROM {base}\n\n"
        f'SYSTEM """{system}\n"""\n\n'
        "# Low temperature: this operator wants derivations, direct answers, and\n"
        "# exact schemas, not creative variety or prolonged thinking chains.\n"
        f"PARAMETER temperature {temp}\n"
        "PARAMETER top_p 0.9\n"
        f"PARAMETER num_ctx {num_ctx}\n"
    )


def _normalise(text: str) -> str:
    """Collapse whitespace so cosmetic reformatting is not read as a change."""
    return " ".join(text.split())


def installed_system(tag: str) -> str | None:
    """The SYSTEM block currently baked into a tag, or None if it has none.

    `ollama show --modelfile` prints it as SYSTEM \"\"\"...\"\"\". Reading it back is
    how we detect the two ways a profile goes wrong: an `ollama pull` replaced
    the manifest and dropped it, or the profile files changed and the tag still
    carries yesterday's text.
    """
    ollama_cmd = "ollama.exe" if sys.platform == "win32" else "ollama"
    proc = subprocess.run([ollama_cmd, "show", "--modelfile", tag],
                          check=False, capture_output=True, text=True, encoding="utf-8",
                          errors="replace")
    if proc.returncode != 0:
        return None
    m = re.search(r'SYSTEM\s+"""(.*?)"""', proc.stdout, re.DOTALL)
    return m.group(1) if m else None


def audit(system: str) -> list[tuple[str, str, str]]:
    """(key, tag, state) for every target. state: ok | stale | missing | absent."""
    want = _normalise(system)
    rows: list[tuple[str, str, str]] = []
    for key, (_base, derived) in sorted(TARGETS.items()):
        have = installed_system(derived)
        if have is None:
            # Distinguish "tag exists without a profile" from "no such tag".
            ollama_cmd = "ollama.exe" if sys.platform == "win32" else "ollama"
            exists = subprocess.run([ollama_cmd, "show", derived],
                                    check=False, capture_output=True, text=True).returncode == 0
            rows.append((key, derived, "missing" if exists else "absent"))
        elif _normalise(have) == want:
            rows.append((key, derived, "ok"))
        else:
            rows.append((key, derived, "stale"))
    return rows


def build(key: str, system: str, *, dry_run: bool, temperature: float | None = None) -> bool:
    base, derived = TARGETS[key]
    BUILD_DIR.mkdir(exist_ok=True)
    path = BUILD_DIR / f"Modelfile.{key}"
    path.write_text(modelfile(base, system, derived, temperature=temperature), encoding="utf-8")

    if dry_run:
        print(f"[dry-run] ollama create {derived} -f {path}")
        return True

    print(f"-> {derived}  (from {base})")
    ollama_cmd = "ollama.exe" if sys.platform == "win32" else "ollama"
    proc = subprocess.run(
        [ollama_cmd, "create", derived, "-f", str(path)],
        check=False,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        print(f"   FAILED: {proc.stderr.strip()[:400]}", file=sys.stderr)
        return False
    return True


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    p.add_argument("--model", choices=sorted(TARGETS), action="append",
                   help="Build only this one (repeatable). Default: all.")
    p.add_argument("--show", action="store_true",
                   help="Print the SYSTEM block and exit.")
    p.add_argument("--dry-run", action="store_true",
                   help="Write the Modelfiles but do not call ollama.")
    p.add_argument("--include-repos", action="store_true",
                   help="Include the full 38-table REPOS.md dump (adds ~3k tokens).")
    p.add_argument("--full", action="store_true",
                   help="Use the complete profile instead of the lean block. "
                        "Costs ~1.1k more prompt tokens on every request.")
    p.add_argument("--no-lifeos", action="store_true",
                   help="Omit the LifeOS operating contract from the SYSTEM block.")
    p.add_argument("--temperature", type=float, default=None,
                   help="Override per-model temperature (default 0.3, or 0.2 for tools/vision).")
    p.add_argument("--print-adopt", action="store_true",
                   help="Print upstream->srini tag mapping as JSON and exit.")
    p.add_argument("--verify", action="store_true",
                   help="Report which tags carry the current profile. Exits "
                        "non-zero if any is missing or stale, so it can gate CI "
                        "or a startup check.")
    p.add_argument("--repair", action="store_true",
                   help="Rebuild only the tags whose profile is missing or "
                        "stale. Safe and cheap to run on every Ollama start - "
                        "an `ollama pull` silently drops the SYSTEM block.")
    args = p.parse_args()

    if args.print_adopt:
        import json
        print(json.dumps(UPSTREAM_ADOPT))
        return 0

    if not PROFILE.exists():
        print(f"missing profile: {PROFILE}", file=sys.stderr)
        return 1

    system = system_block(
        include_repos=args.include_repos,
        lean=not args.full,
        include_lifeos=not args.no_lifeos,
    )

    if args.show:
        print(system)
        print(f"\n[{len(system)} chars ~= {len(system) // 4} tokens]",
              file=sys.stderr)
        return 0

    if args.verify or args.repair:
        rows = audit(system)
        for key, tag, state in rows:
            mark = {"ok": "  ok", "stale": "  STALE", "missing": "  MISSING",
                    "absent": "  (not pulled)"}[state]
            print(f"{mark:<16}{tag}")
        broken = [(k, t) for k, t, s in rows if s in ("stale", "missing")]
        if not broken:
            print(f"\nall profiled tags current ({len(system) // 4} tokens)")
            return 0
        if args.verify:
            print(f"\n{len(broken)} tag(s) need rebuilding - rerun with --repair")
            return 1
        print(f"\nrepairing {len(broken)} tag(s)")
        ok = all(build(k, system, dry_run=args.dry_run, temperature=args.temperature) for k, _ in broken)
        return 0 if ok else 1

    keys = args.model or sorted(TARGETS)
    ok = all(build(k, system, dry_run=args.dry_run, temperature=args.temperature) for k in keys)
    if ok and not args.dry_run:
        print(f"\nDone. {len(system) // 4} tokens of context, resident in every "
              f"session of every tag built above.")
        print("Try: python ask_local_llm.py --model srini-coder:9b "
              '"How much VRAM can I spend on a QLoRA run right now?"')
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
