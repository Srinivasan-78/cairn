#!/usr/bin/env python3
"""
sync_repos.py - Regenerate profile/REPOS.md from the GitHub account.

The repository inventory is the part of the profile that goes stale fastest: a
new repo, a rename, or an archive makes a hand-written list wrong, and a wrong
fact in a system prompt is worse than a missing one because the model states it
confidently. So this is generated, not written. Re-run it whenever the account
changes, then rebuild the persona tags.

Needs `gh` authenticated as the account owner - private repos are included, so
the output stays on this machine (it is baked into local Ollama tags only).

Usage:
    python profile/sync_repos.py                 # write profile/REPOS.md
    python profile/sync_repos.py --owner someone
    python profile/sync_repos.py --dry-run       # print, do not write
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

OUT = Path(__file__).with_name("REPOS.md")

REPO_FIELDS = ("name,isFork,isPrivate,isArchived,primaryLanguage,description,"
               "pushedAt,stargazerCount,parent")


def gh_json(args: list[str]):
    """Run a gh command that returns JSON, or exit with its error.

    `encoding="utf-8"` is not optional: without it subprocess decodes with the
    Windows locale default (cp1252) and every em dash in a repo description
    arrives as mojibake - which then gets baked into the model's system prompt.
    """
    proc = subprocess.run(["gh", *args], check=False, capture_output=True, text=True,
                          encoding="utf-8", errors="replace")
    if proc.returncode != 0:
        raise SystemExit(f"gh failed: {' '.join(args)}\n{proc.stderr.strip()[:400]}")
    return json.loads(proc.stdout or "[]")


def fork_parents(owner: str, forks: list[dict]) -> dict[str, str]:
    """Upstream repo for each fork.

    `gh repo list` accepts `parent` as a field but returns it empty, so the
    parent has to be read per repository. Knowing the upstream is the whole
    point of listing a fork - `linux` and `Pumpkin` mean nothing without it.
    """
    parents: dict[str, str] = {}
    for r in forks:
        name = r["name"]
        try:
            data = gh_json(["repo", "view", f"{owner}/{name}", "--json", "parent"])
        except SystemExit:
            parents[name] = "unknown"
            continue
        parent = (data or {}).get("parent") or {}
        if parent.get("owner") and parent.get("name"):
            owner_login = parent["owner"].get("login") or parent["owner"]
            parents[name] = f"{owner_login}/{parent['name']}"
        else:
            parents[name] = parent.get("nameWithOwner") or "unknown"
    return parents


def pr_counts(owner: str) -> Counter:
    """PRs authored per repository. One search call, capped at the API's limit."""
    rows = gh_json(["search", "prs", f"--author={owner}", "--limit", "500",
                    "--json", "repository"])
    if len(rows) >= 500:
        print("WARN: gh search prs hit 500-row cap; PR counts may be truncated.",
              file=sys.stderr)
    return Counter(r["repository"]["name"] for r in rows)


def lang(repo: dict) -> str:
    return (repo.get("primaryLanguage") or {}).get("name") or "-"


def desc(repo: dict, width: int = 96) -> str:
    d = (repo.get("description") or "").strip().replace("|", "/")
    return (d[: width - 1] + "…") if len(d) > width else (d or "-")


def render(owner: str, repos: list[dict], prs: Counter,
           parents: dict[str, str]) -> str:
    active = [r for r in repos if not r["isFork"] and not r["isArchived"]]
    archived = [r for r in repos if not r["isFork"] and r["isArchived"]]
    forks = [r for r in repos if r["isFork"]]

    active.sort(key=lambda r: (-prs.get(r["name"], 0), r.get("pushedAt") or ""))
    archived.sort(key=lambda r: r.get("pushedAt") or "", reverse=True)
    forks.sort(key=lambda r: r.get("pushedAt") or "", reverse=True)

    out: list[str] = []
    add = out.append

    add(f"# Repository inventory - github.com/{owner}")
    add("")
    add(f"Generated by `profile/sync_repos.py` on {date.today().isoformat()}. "
        "Do not hand-edit: re-run the script and rebuild the persona tags. "
        "Counts below are facts as of that date and will drift.")
    add("")
    add(f"**{len(repos)} repositories** - {len(active)} active original, "
        f"{len(archived)} archived, {len(forks)} forks. "
        f"{sum(1 for r in repos if r['isPrivate'])} private. "
        f"{sum(r['stargazerCount'] for r in repos)} stars total.")
    add("")
    add("A fork is upstream code, not work authored here - do not describe a "
        "fork's contents as the operator's own design decisions.")
    add("")

    add("## Active original repositories")
    add("")
    add("| repo | lang | PRs | private | pushed | what it is |")
    add("|---|---|---|---|---|---|")
    for r in active:
        add(f"| `{r['name']}` | {lang(r)} | {prs.get(r['name'], 0) or '-'} "
            f"| {'yes' if r['isPrivate'] else 'no'} "
            f"| {(r.get('pushedAt') or '')[:10]} | {desc(r)} |")
    add("")

    if archived:
        add("## Archived (read-only; do not propose changes)")
        add("")
        add("| repo | lang | pushed | what it was |")
        add("|---|---|---|---|")
        for r in archived:
            add(f"| `{r['name']}` | {lang(r)} | {(r.get('pushedAt') or '')[:10]} "
                f"| {desc(r, 72)} |")
        add("")

    if forks:
        add("## Forks (upstream code)")
        add("")
        add("| fork | upstream | lang |")
        add("|---|---|---|")
        for r in forks:
            add(f"| `{r['name']}` | `{parents.get(r['name'], 'unknown')}` "
                f"| {lang(r)} |")
        add("")

    langs = Counter(lang(r) for r in repos if lang(r) != "-")
    add("## Shape of the portfolio")
    add("")
    add("- Languages by repo count: "
        + ", ".join(f"{k} {v}" for k, v in langs.most_common(8)) + ".")
    busiest = [f"`{r['name']}` ({prs[r['name']]})" for r in active[:5]
               if prs.get(r["name"])]
    if busiest:
        add("- Most PR activity: " + ", ".join(busiest) + ".")
    add(f"- {sum(1 for r in repos if r['isPrivate'])} of {len(repos)} "
        "repositories are private, so their names appear here but their "
        "contents are not public - do not suggest linking to them.")
    add("")
    return "\n".join(out)


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    p.add_argument("--owner", default="Srinivasan-78")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args()

    repos = gh_json(["repo", "list", args.owner, "--limit", "500",
                     "--json", REPO_FIELDS])
    if not repos:
        raise SystemExit(f"no repositories returned for {args.owner}")

    forks = [r for r in repos if r["isFork"]]
    text = render(args.owner, repos, pr_counts(args.owner),
                  fork_parents(args.owner, forks))

    if args.dry_run:
        print(text)
        return 0

    OUT.write_text(text + "\n", encoding="utf-8")
    print(f"wrote {OUT}  ({len(text)} chars ~= {len(text) // 4} tokens, "
          f"{len(repos)} repos)")
    print("now run: python profile/build_persona_models.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
